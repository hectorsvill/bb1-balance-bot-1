"""gen_docs.py - put the agent manual and the API reference inside the firmware.

    python3 tools/gen_docs.py            # write firmware/bb1/docs_pages.h
    python3 tools/gen_docs.py --check    # exit 1 if docs_pages.h is older than the .md files (CI)

BB1 serves two Markdown pages so an agent with only curl can learn to drive it:
    GET /agent    = docs/AGENT.md  (how to drive it safely)
    GET /api.md   = docs/API.md    (every endpoint, with curl)
(GET /api stays the JSON list built from the table in api.h.)

The .md files are the only copy we write by hand. This script turns each one into
a C++ raw string in firmware/bb1/docs_pages.h, which web.h sends as it is. The
strings live in flash (const), not RAM, like the web page in page.h.

docs_pages.h is committed so the Arduino IDE and CI build without running this
first, but never edit it: edit the .md and run this script. tools/flash.py runs
it before every compile, and CI (--check) fails if someone forgot.

Only the Python standard library is used (CI runs it without the venv).
Exit codes: 0 ok, 1 out of date (--check) or a doc can't be embedded.
"""

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "firmware" / "bb1" / "docs_pages.h"

# (C++ name, source file, served at). Add a page here and a route in web.h.
PAGES = [
    ("AGENT_MD", "docs/AGENT.md", "/agent"),
    ("API_MD", "docs/API.md", "/api.md"),
]

# Ends the raw string R"BB1DOC( ... )BB1DOC". A doc can't contain it.
END = ')BB1DOC"'


def render():
    """The whole docs_pages.h as text."""
    out = [
        "// docs_pages.h - GENERATED by tools/gen_docs.py. Do not edit this file:",
        "// edit the .md files in docs/ and run  python3 tools/gen_docs.py",
        "// (tools/flash.py runs it before every compile; CI checks it is current).",
        "//",
        "// Each doc is one raw string, sent as it is by web.h. const = kept in flash, not RAM.",
        "",
        "#pragma once",
        "",
    ]
    for name, src, path in PAGES:
        text = (REPO / src).read_text(encoding="utf-8")
        if END in text:
            raise ValueError(f"{src} contains {END!r}, which would end the C++ string early")
        out.append(f"// {path} <- {src} ({len(text.encode('utf-8'))} bytes)")
        out.append(f'const char {name}[] = R"BB1DOC({text}{END};')
        out.append("")
    return "\n".join(out)


def write():
    """Write docs_pages.h if it changed; returns what happened (one line).
    Raises ValueError if a doc can't be embedded. tools/flash.py calls this."""
    text = render()
    if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
        return f"{OUT.relative_to(REPO)} already current"
    OUT.write_text(text, encoding="utf-8")
    return f"wrote {OUT.relative_to(REPO)}"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="don't write; exit 1 if docs_pages.h is out of date")
    args = ap.parse_args(argv)
    try:
        if not args.check:
            print(write())
            return 0
        text = render()
    except ValueError as e:
        print(e, file=sys.stderr)
        return 1
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if current != text:
        print("firmware/bb1/docs_pages.h is out of date: run  python3 tools/gen_docs.py  and commit it.",
              file=sys.stderr)
        return 1
    print("firmware/bb1/docs_pages.h matches docs/AGENT.md and docs/API.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
